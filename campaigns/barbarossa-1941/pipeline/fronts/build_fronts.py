def R(name, a, b, step=12.0, off=0.0):
    """河段 a→b（含端点附近的河道点）"""
    return geo.river(name, a, b, step=step, offset=off)


def circle(c, rkm, n=12, rot=0.0, ry=None):
    """以 c 为中心、半径 rkm 的近似圆环（ry 给出南北半径则为椭圆）"""
    ry = ry or rkm
    k = math.cos(math.radians(c[1])) * 111.32
    return [[round(c[0] + rkm * math.cos(2 * math.pi * i / n + rot) / k, 3), round(c[1] + ry * math.sin(2 * math.pi * i / n + rot) / 110.57, 3)] for i in range(n)]


def flat(*parts):
    out = []
    for p in parts:
        if p and isinstance(p[0], (int, float)):
            out.append(p)
        else:
            for q in p:
                out.append(q)
    # 去掉重复的相邻点
    res = []
    for q in out:
        q = [round(q[0], 3), round(q[1], 3)]
        if not res or res[-1] != q:
            res.append(q)
    return res


