def de_poly(ring, holes=(), extra=()):
    """DE：外环（北端起点 … 南端）+ 西侧竖线闭合，外加洞；extra 为额外的独立小多边形（如普鲁特河桥头堡）"""
    r = flat(ring)
    assert abs(r[-1][1] - SOUTH) < 1e-6, f'DE 外环须在 {SOUTH}°N 结束：{r[-1]}'
    r = r + [[WEST, SOUTH], [WEST, r[0][1]]]
    return [[r] + [flat(h) for h in holes]] + [[flat(e)] for e in extra]


