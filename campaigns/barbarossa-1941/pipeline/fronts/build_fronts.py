def write():
    os.makedirs(OUT, exist_ok=True)
    keep = set()
    prev = None
    for k in sorted(KF, key=lambda k: k['at']):
        assert prev is None or k['at'] > prev, k['at']
        prev = k['at']
        control = {}
        if k['de']:
            control['DE'] = k['de']
        if k['fi']:
            control['FI'] = k['fi']
        o = {'at': k['at'], 'control': control}
        if k['step']:
            o['transition'] = 'step'
        o.update(note=k['note'], sources=k['src'], confidence=k['conf'])
        fn = os.path.join(OUT, k['at'].replace(':', '-') + '.json')
        keep.add(os.path.basename(fn))
        txt = json.dumps(o, ensure_ascii=False, indent=1)
        # 坐标对压成一行，便于阅读
        import re
        txt = re.sub(r'\[\n\s+(-?[\d.]+),\n\s+(-?[\d.]+)\n\s+\]', r'[\1, \2]', txt)
        with open(fn, 'w', encoding='utf-8') as f:
            f.write(txt + '\n')
    for fn in os.listdir(OUT):
        if fn.endswith('.json') and fn not in keep:
            os.remove(os.path.join(OUT, fn))
            print('删除旧关键帧', fn)
    print(f'{len(KF)} 个关键帧 → {OUT}')


if __name__ == '__main__':
    write()
