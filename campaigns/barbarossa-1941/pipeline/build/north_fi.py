def build():
    gaz = load_gaz()
    fix_models(U)
    # 集结后长时间不动的部队：在发起进攻前一天补一个原地点，避免插值越过国界
    from north_lib import iso, hours
    import datetime
    for u in U:
        tr = u['track']
        if len(tr) >= 2 and tr[1]['at'] in ('1941-07-10T02:00', '1941-07-31T04:00', '1941-08-22T04:00') \
                and hours(tr[1]['at']) - hours(tr[0]['at']) > 72:
            t1 = datetime.datetime.strptime(tr[1]['at'], '%Y-%m-%dT%H:%M') - datetime.timedelta(hours=8)
            tr.insert(1, {'at': t1.strftime('%Y-%m-%dT%H:%M'), 'pos': tr[0]['pos']})
    snap_axis_to_fronts(U, gaz)
    for u in U:
        if u.get('model') is None:
            u.pop('model', None)
    n = check_units(U, gaz)
    ids = [u['id'] for u in U]
    assert len(ids) == len(set(ids)), 'dup ids'
    write('data/oob/fi.json', U)
    print('fi:', len(U), 'units;', n, 'issues')


if __name__ == '__main__':
    build()
