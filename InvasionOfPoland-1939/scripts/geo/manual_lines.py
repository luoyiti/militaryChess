CACHE = os.path.join(WORK, 'traced.json')


def get_traced():
    key = hashlib.md5(json.dumps(WAYPOINTS, sort_keys=True).encode()).hexdigest()
    if os.path.exists(CACHE):
        c = json.load(open(CACHE))
        if c.get('_key') == key:
            return c['lines']
    import trace
    lines = {}
    for k, (mode, wp) in WAYPOINTS.items():
        lines[k] = trace.trace(wp, mode)
        print(f'  [trace] {k}: {len(wp)} 航点 → {len(lines[k])} 点')
    json.dump({'_key': key, 'lines': lines}, open(CACHE, 'w'))
    return lines


if __name__ == '__main__':
    get_traced()
